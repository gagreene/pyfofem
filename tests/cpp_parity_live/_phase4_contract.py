def golden_rows_by_case(mode: str, suffix: str = "") -> Dict[str, Dict[str, str]]:
    """
    Read a committed Phase 4 golden output CSV keyed by ``case_id``.

    :param mode: Harness mode name.
    :param suffix: Output-file suffix.
    :returns: ``{case_id: row}``.
    :raises FileNotFoundError: Via :func:`golden_rows`.
    :raises ValueError: If two rows share a ``case_id`` (the golden's own
        one-output-per-input reconciliation would already have failed, so
        this is a fail-closed backstop).
    """
    out: Dict[str, Dict[str, str]] = {}
    for row in golden_rows(mode, suffix):
        case_id = row["case_id"]
        if case_id in out:
            raise ValueError(
                f"duplicate case_id {case_id!r} in {mode}{suffix}.csv"
            )
        out[case_id] = row
    return out


def missing_golden_files() -> List[str]:
    """
    Return every required Phase 4 golden file that is absent or empty.

    Deliberately returns the exact repo-relative paths rather than a boolean:
    a broken checkout must produce an actionable message naming the files,
    never a silent skip. See :func:`require_golden_tree`.

    :returns: Repo-relative paths, sorted, of every required file that does
        not exist or exists with zero bytes.
    """
    missing = []
    for mode in PHASE4_MODES:
        for path in _required_golden_files(mode):
            if not os.path.isfile(path) or os.path.getsize(path) == 0:
                missing.append(
                    os.path.relpath(path, PROJECT_ROOT).replace(os.sep, "/")
                )
    return sorted(missing)


def phase4_approx_kwargs(mode: str, route: str) -> Dict[str, float]:
    """
    Return the ``pytest.approx`` keyword arguments for one Phase 4 output
    route, built from the centrally recorded tolerance.

    A bound that :func:`phase4_tolerance` reports as ``None`` is OMITTED
    rather than passed as ``None``, so the resulting comparison has exactly
    the semantics the policy records:

    - ``atol`` only -> a pure absolute comparison;
    - ``rtol`` only -> a relative comparison against ``pytest.approx``'s own
      default absolute floor;
    - both -> ``max(rtol * expected, atol)``, ``pytest.approx``'s standard
      combined rule.

    :param mode: Harness mode name; the ``_p4`` suffix is added downstream.
    :param route: Route key within that mode's Phase 4 policy section.
    :returns: ``{"abs": atol}``, ``{"rel": rtol}`` or both - never empty,
        because :func:`phase4_tolerance` guarantees at least one bound.
    :raises KeyError: If the section or route does not exist.
    :raises ValueError: Via :func:`phase4_tolerance`, if no bound can be
        resolved.
    """
    atol, rtol = phase4_tolerance(mode, route)
    kwargs: Dict[str, float] = {}
    if atol is not None:
        kwargs["abs"] = atol
    if rtol is not None:
        kwargs["rel"] = rtol
    return kwargs


