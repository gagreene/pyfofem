def phase4_tolerance(
        mode: str,
        route: str,
) -> Tuple[Optional[float], Optional[float]]:
    """
    Return the centrally recorded ``(atol, rtol)`` for one Phase 4 output
    route.

    This is the ONLY way a Phase 4 parity test may obtain a tolerance for a
    Python-vs-C++ golden comparison: the number, its unit and the measured
    evidence that justifies it live in ``tolerance_policy.json``, never as a
    literal in a test module.

    A route whose own entry records no bound falls back to the single sibling
    entry sharing its declared ``column_group`` that does record one. That
    fallback is deliberate and narrow: entries sharing a ``column_group``
    classify the SAME output column of the SAME file by equation route, so a
    bound derived from that column's own output resolution is a property of
    the column rather than of the route (e.g. ``litter_eq_p4.997``, whose
    divergence no tolerance can honestly bound, still needs the ``con_tac``
    column's resolution bound to express its desired-behaviour assertion).
    Anything else fails closed.

    :param mode: Harness mode name; the ``_p4`` suffix is added here.
    :param route: Route key within that mode's Phase 4 policy section.
    :returns: ``(atol, rtol)``, at least one of which is not ``None``.
    :raises KeyError: If the section or route does not exist.
    :raises ValueError: If neither the entry nor exactly one ``column_group``
        sibling records a tolerance.
    """
    section = f"{mode}_p4"
    policy = load_tolerance_policy()
    if section not in policy:
        raise KeyError(f"no Phase 4 tolerance-policy section {section!r}")
    entries = policy[section]
    if route not in entries:
        raise KeyError(f"no route {route!r} in policy section {section!r}")
    entry = entries[route]
    if entry.get("atol") is not None or entry.get("rtol") is not None:
        return entry.get("atol"), entry.get("rtol")

    group = entry.get("column_group")
    if group is None:
        raise ValueError(
            f"{section}.{route} records no atol/rtol and declares no "
            "column_group, so no bound can be resolved for it - record the "
            "measured evidence in tolerance_policy.json rather than "
            "hardcoding a number in a test"
        )
    siblings = [
        (name, other) for name, other in entries.items()
        if name != route
        and other.get("column_group") == group
        and (other.get("atol") is not None or other.get("rtol") is not None)
    ]
    if len(siblings) != 1:
        raise ValueError(
            f"{section}.{route} records no atol/rtol and its column_group "
            f"{group!r} has {len(siblings)} sibling entries that do; exactly "
            "one is required for the fallback to be unambiguous"
        )
    _name, sibling = siblings[0]
    return sibling.get("atol"), sibling.get("rtol")


def python_contract_epsilon(name: str) -> float:
    """
    Return a named class-(a) PYTHON-SIDE tolerance.

    Separate from :func:`phase4_tolerance` on purpose: these bound
    Python-vs-Python or Python-vs-transcribed-constant comparisons and make
    no executable C++ parity claim, so they are not evidence records in
    ``tolerance_policy.json``.

    :param name: Key in :data:`PYTHON_CONTRACT_EPSILONS`.
    :returns: The epsilon.
    :raises KeyError: If *name* is not registered - a test may not invent an
        unnamed epsilon.
    """
    if name not in PYTHON_CONTRACT_EPSILONS:
        raise KeyError(
            f"unregistered Python-contract epsilon {name!r}; add it to "
            "PYTHON_CONTRACT_EPSILONS with a comment saying what it bounds"
        )
    return PYTHON_CONTRACT_EPSILONS[name]


def require_golden_tree() -> None:
    """
    Fail closed unless the complete committed Phase 4 golden dataset is
    present.

    A missing, empty or partially checked-out Phase 4 golden dataset is a
    REPOSITORY defect, not an environment difference: the dataset is
    committed (see the ``.gitignore`` negations for
    ``tests/test_data/test_golden_output/phase4/``), so a correct checkout
    always has it. Every Phase 4 parity module calls this at import time, so
    the failure surfaces as a loud collection error naming the exact missing
    files rather than as a silent skip.

    :returns: None.
    :raises FileNotFoundError: If any required file is missing or empty.
    """
    missing = missing_golden_files()
    if missing:
        raise FileNotFoundError(
            "the committed Phase 4 golden dataset is incomplete - this is a "
            "repository defect, not a skippable environment difference. "
            "Missing or empty:\n"
            + "\n".join(f"  - {path}" for path in missing)
            + "\nRestore them from git, or regenerate with "
              "tests/cpp_parity_live/generate_phase4_goldens.py (needs the "
              "live MSVC/CMake/Ninja toolchain)."
        )
