def test_scorch_ht_scalar_matches_length_one_array():
    """
    A scalar call and a length-one array call must agree, for all three
    equations.

    :return: None. Raises via ``assert`` on mismatch.
    """
    cases = ((1000.0,), (1000.0, 20.0), (1000.0, 20.0, 2.0))
    for args in cases:
        scalar = float(calc_scorch_ht(*args))
        arrayed = calc_scorch_ht(np.array([args[0]]), *args[1:])
        assert arrayed.shape == (1,)
        _assert_close(float(arrayed[0]), scalar)


def test_scorch_ht_zero_intensity_is_zero():
    """
    Zero fire intensity yields zero scorch height in equations 8 and 9.

    Equation 10 is excluded: at ``sfi == 0`` and ``ws == 0`` its
    denominator is also zero, which is a separate degenerate case not
    claimed by this test.

    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_scorch_ht(0.0)), 0.0)
    _assert_close(float(calc_scorch_ht(0.0, 20.0)), 0.0)
