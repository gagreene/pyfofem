def test_scorch_ht_equation_8_selected_whenever_amb_t_is_none():
    """
    Mode selection is driven by ``amb_t`` alone: supplying
    ``instand_ws`` without ``amb_t`` still selects equation 8, so the
    windspeed argument is silently ignored.

    Pinned because it is a real, undocumented API trap - a caller who
    passes only a windspeed gets the no-wind equation with no warning.

    :return: None. Raises via ``assert`` on mismatch.
    """
    with_wind = float(calc_scorch_ht(1000.0, None, 3.0))
    without_wind = float(calc_scorch_ht(1000.0))
    _assert_close(with_wind, without_wind)
    _assert_close(with_wind, 0.1483 * 100.0)


