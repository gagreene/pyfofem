        (1000.0, 20.0, 4.4713 * 100.0 / 40.0),      # = 11.178250
        (8000.0, 10.0, 4.4713 * 400.0 / 50.0),      # = 35.770400
        (27000.0, 35.0, 4.4713 * 900.0 / 25.0),     # = 160.966800
        (125.0, 0.0, 4.4713 * 25.0 / 60.0),         # =  1.863042
