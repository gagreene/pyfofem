@pytest.mark.parametrize(
    "fl_model",
    ["byram", "BYRAM", "butler", "Thomas", "", "not-a-model", "Van Wagner"],
)
def test_flame_length_unrecognised_model_silently_selects_thomas(fl_model):
    """
    Pin Gate 0 finding **F-28**: ``fl_model`` is dispatched with
    ``if 'Byram' / if 'Butler' / else`` in ``tree_flame_calcs.py``, so
    any string that is neither the exact ``'Byram'`` nor the exact
    ``'Butler'`` - including a case variant or an outright typo - falls
    through to the Thomas equation instead of raising. This test
    documents that divergence from a fail-fast contract; it does not
    endorse it.

    :param fl_model: Model string that is not exactly ``'Byram'`` or
        ``'Butler'``.
    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_flame_length(1000.0, fl_model=fl_model)), 2.67)


def test_flame_length_zero_intensity_is_zero():
    """
    Zero fire intensity yields zero flame length in every
    fire-intensity mode (``0 ** p == 0`` for positive ``p``).

    :return: None. Raises via ``assert`` on mismatch.
    """
    for model in ("Byram", "Butler", "Thomas"):
        _assert_close(float(calc_flame_length(0.0, fl_model=model)), 0.0)


def test_scorch_ht_ambient_60_divides_by_zero():
    """
    Pin the second half of Gate 0 finding **F-24**: equations 9 and 10
    divide by ``(60 - amb_t)`` with no guard, so an ambient temperature
    of exactly 60 C yields ``inf`` plus a NumPy ``RuntimeWarning``
    instead of a diagnosed error.

    :return: None. Raises via ``assert`` on mismatch.
    """
    with pytest.warns(RuntimeWarning, match="divide by zero"):
        eq9 = calc_scorch_ht(1000.0, 60.0)
    assert np.isinf(eq9)

    with pytest.warns(RuntimeWarning, match="divide by zero"):
        eq10 = calc_scorch_ht(1000.0, 60.0, 2.0)
    assert np.isinf(eq10)


def test_scorch_ht_ambient_above_60_returns_negative_height():
    """
    An ambient temperature above 60 C flips the sign of the equation-9
    denominator and returns a physically meaningless negative scorch
    height rather than raising or clamping.

    Pinned as current behaviour so a future domain guard is a visible,
    deliberate change. Hand-derived at ``sfi = 1000``, ``amb_t = 80``:
    ``4.4713 * 100 / (60 - 80) = 447.13 / -20 = -22.3565``.

    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_scorch_ht(1000.0, 80.0)), -22.3565)


def test_scorch_ht_array_broadcast_matches_row_by_row():
    """
    Array evaluation of equations 9 and 10 must equal row-by-row scalar
    evaluation of the same inputs, an oracle-independent metamorphic
    property required by the phase plan.

    :return: None. Raises via ``assert`` on mismatch.
    """
    sfi = np.array([1000.0, 8000.0, 27000.0])
    amb = np.array([20.0, 10.0, 35.0])
    wind = np.array([1.0, 2.0, 3.0])

    eq9_vec = calc_scorch_ht(sfi, amb)
    for i in range(len(sfi)):
        _assert_close(float(eq9_vec[i]), float(calc_scorch_ht(sfi[i], amb[i])))

    eq10_vec = calc_scorch_ht(sfi, amb, wind)
    for i in range(len(sfi)):
        _assert_close(
            float(eq10_vec[i]), float(calc_scorch_ht(sfi[i], amb[i], wind[i]))
        )


def test_scorch_ht_equation_10_hand_derived_value():
    """
    Equation 10 must evaluate
    ``0.74183 * I**(7/6) / (sqrt(0.025574*I + 0.021433*ws**3) * (60 - T))``.

    Hand derivation at ``I = 1000`` kW/m, ``ws = 2`` m/s, ``T = 20`` C:

    * ``1000 ** (7/6) = 1000 * 1000 ** (1/6) = 1000 * 3.1622776601683795
      = 3162.2776601683795``  (``1000 ** (1/6) == 10 ** 0.5``)
    * numerator ``= 0.74183 * 3162.2776601683795 = 2345.8317...``
    * inner ``= 0.025574 * 1000 + 0.021433 * 2**3
      = 25.574 + 0.171464 = 25.745464``
    * ``sqrt(25.745464) = 5.0739988...``
    * denominator ``= 5.0739988... * (60 - 20) = 202.9599...``
    * result ``= 11.558302046462384``

    The final value is frozen as a literal so this test compares against
    a hand-carried number rather than re-running the implementation's
    own expression.

    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_scorch_ht(1000.0, 20.0, 2.0)), 11.558302046462384)


