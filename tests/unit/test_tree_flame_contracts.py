#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
test_tree_flame_contracts.py - Phase 3 public-contract coverage for
``calc_scorch_ht`` and ``calc_flame_length``.

**Test-category classification** (see the phase plan
``development/plans/2026-08-26-comprehensive-test-suite-plan.md``):

(a) *Python contract/equation test* - asserts documented equations, or
    explicitly identified current Python behaviour including known
    contract defects pinned for visibility, against hand-derived
    expected values. Makes no C++ parity claim, and does not endorse
    defective behaviour as desired API design. **Every test in this
    module is category (a)**; several of them pin findings F-24, F-28,
    F-33 and F-34, which are undocumented or defective current
    behaviour recorded for visibility, not endorsed API design.
(b) *Source-relation cross-check* - hand-derived against a pinned C++
    expression that is not executable in isolation. **None here**; the
    tree/flame source-relation tests live in
    ``tests/unit/test_tree_flame_source_relations.py``.
(c) *Executable C++ parity* - compares against output generated by a
    live pinned-C++ run. **None here, and deliberately so.**

Gate 0 established that C++ ``Calc_Scorch`` (``fof_util.cpp:95-102``)
converts *flame length to scorch height*, and ``Calc_Flame``
(``fof_util.cpp:111-118``) converts *scorch height back to flame
length* - both through the same 0.45/power relationship. Python's
``calc_scorch_ht`` takes *fire intensity* plus optional ambient
temperature and in-stand windspeed, and ``calc_flame_length``'s
fire-intensity modes use Byram / Butler / Thomas equations. They are
different APIs with different inputs and must never be compared as
parity oracles (``gate0/03-cpp-crosswalk.md`` rows 6 and 7). No C++
comparison is therefore attempted anywhere in this module.

Two contract defects recorded by Gate 0 are pinned here as *current
behaviour*, with the divergence stated explicitly rather than hidden:

* **F-24** - ``calc_scorch_ht``'s ``(60 - amb_t)`` denominator has no
  guard, so equations 9 and 10 divide by zero at ``amb_t == 60``.
  Also, the missing-intensity guard is **not** fully dead code; see
  :func:`test_scorch_ht_missing_intensity_guard_fires_for_object_dtype`
  and its inert-for-numeric counterpart.
* **F-28** - ``calc_flame_length`` dispatches ``fl_model`` with
  ``if 'Byram' / if 'Butler' / else``, so any unrecognised string
  (including a typo such as ``'byram'``) silently selects Thomas.

Function order: private helpers first, then public test functions, each
group alphabetized, per AGENTS.md.
"""
from __future__ import annotations

import numpy as np
import pytest

from pyfofem import calc_flame_length, calc_scorch_ht

#: Fire intensities (kW/m) whose two-thirds power is an exact integer, so
#: every equation-8/9 expectation below is a literal hand-computed value
#: rather than a re-execution of the implementation's own expression:
#: ``1 ** (2/3) == 1``, ``125 ** (2/3) == 25``, ``1000 ** (2/3) == 100``,
#: ``8000 ** (2/3) == 400``, ``27000 ** (2/3) == 900``.
_EXACT_CUBE_INTENSITIES = {
    1.0: 1.0,
    125.0: 25.0,
    1000.0: 100.0,
    8000.0: 400.0,
    27000.0: 900.0,
}


def _assert_close(actual: float, expected: float, rel: float = 1e-12) -> None:
    """
    Assert a scalar result matches a hand-derived expectation.

    A relative tolerance of 1e-12 is used rather than an absolute one so
    the same helper serves both the small (metres) and large (percent)
    magnitudes in this module. The tolerance is a floating-point
    round-off allowance only - these are exact closed-form expectations,
    not measurements, so nothing scientific is being absorbed by it.

    :param actual: Value returned by the function under test.
    :param expected: Hand-derived expected value.
    :param rel: Relative tolerance passed through to
        :func:`pytest.approx`.
    :return: None. Raises via ``assert`` on mismatch.
    """
    assert actual == pytest.approx(expected, rel=rel)


def test_flame_length_butler_hand_derived_values():
    """
    Butler mode must evaluate ``0.0175 * I ** (2/3)`` exactly.

    Hand-derived on the exact-cube intensities: ``0.0175 * 100 = 1.75``,
    ``0.0175 * 400 = 7.0``, ``0.0175 * 900 = 15.75``.

    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_flame_length(1000.0, fl_model="Butler")), 1.75)
    _assert_close(float(calc_flame_length(8000.0, fl_model="Butler")), 7.0)
    _assert_close(float(calc_flame_length(27000.0, fl_model="Butler")), 15.75)


def test_flame_length_byram_hand_derived_values():
    """
    Byram mode must evaluate ``0.0775 * I ** 0.46``.

    ``1000 ** 0.46 == 10 ** 1.38 == 23.9883291901949...``; multiplying by
    0.0775 gives the frozen literal below (independently reproduced as
    ``0.0775 * math.exp(0.46 * math.log(1000.0))``, agreeing to within
    4e-16 relative).

    The 8000 kW/m expectation is ``0.0775 * 8000 ** 0.46``, derived the
    same independent way: ``log(8000) = log(8) + log(1000) =
    2.0794415416798357 + 6.907755278982137 = 8.987196820661973``, times
    0.46 gives ``4.134110537504508``, whose exponential times 0.0775 is
    the frozen literal below (the two routes agree to within 5e-16
    relative). Both values are frozen constants, so this test compares
    against hand-carried numbers rather than re-running the
    implementation's own expression.

    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_flame_length(1000.0)), 1.8590955122401054)
    _assert_close(float(calc_flame_length(8000.0)), 4.838637606684622)


def test_flame_length_char_ht_mode_hand_derived_values():
    """
    The char-height mode must evaluate ``char_ht * 1.8`` exactly.

    This is the algebraic inverse of the char-height relation the pinned
    mortality source uses (``fof_mrt.cpp:396-397``); the relation itself
    is cross-checked in
    ``tests/unit/test_tree_flame_source_relations.py``. Here it is
    asserted purely as the Python contract.

    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_flame_length(char_ht=1.0)), 1.8)
    _assert_close(float(calc_flame_length(char_ht=2.5)), 4.5)
    _assert_close(float(calc_flame_length(char_ht=0.0)), 0.0)


def test_flame_length_fire_intensity_takes_precedence_over_char_ht():
    """
    When both ``fire_intensity`` and ``char_ht`` are supplied, the
    fire-intensity branch wins and the char-height argument is ignored.

    Pinned because the function has two independent optional inputs and
    no documented precedence rule; a future refactor that reversed the
    order would silently change results for every caller passing both.

    :return: None. Raises via ``assert`` on mismatch.
    """
    both = float(calc_flame_length(1000.0, char_ht=99.0))
    intensity_only = float(calc_flame_length(1000.0))
    _assert_close(both, intensity_only)


def test_flame_length_negative_intensity_returns_nan():
    """
    A negative fire intensity raised to a fractional power yields NaN
    with a NumPy ``RuntimeWarning`` in every fire-intensity mode.

    Pinned as current behaviour: the function performs no domain
    validation on ``fire_intensity``.

    :return: None. Raises via ``assert`` on mismatch.
    """
    for model in ("Byram", "Butler", "Thomas"):
        with pytest.warns(RuntimeWarning, match="invalid value"):
            result = calc_flame_length(-1.0, fl_model=model)
        assert np.isnan(result)


def test_flame_length_requires_intensity_or_char_ht():
    """
    Calling with neither ``fire_intensity`` nor ``char_ht`` must raise
    ``ValueError`` with the documented diagnostic.

    :return: None. Raises via ``assert`` on mismatch.
    """
    with pytest.raises(ValueError, match="surface fire intensity or char height"):
        calc_flame_length()


def test_flame_length_scalar_matches_length_one_array():
    """
    A scalar call and a length-one array call must agree, for every
    fire-intensity model and for the char-height mode.

    :return: None. Raises via ``assert`` on mismatch.
    """
    for model in ("Byram", "Butler", "Thomas"):
        scalar = float(calc_flame_length(1000.0, fl_model=model))
        arrayed = calc_flame_length(np.array([1000.0]), fl_model=model)
        assert arrayed.shape == (1,)
        _assert_close(float(arrayed[0]), scalar)

    scalar_char = float(calc_flame_length(char_ht=2.0))
    arrayed_char = calc_flame_length(char_ht=np.array([2.0]))
    assert arrayed_char.shape == (1,)
    _assert_close(float(arrayed_char[0]), scalar_char)


