def test_scorch_ht_equation_9_hand_derived_values(sfi, amb_t, expected):
    """
    Equation 9 (``amb_t`` supplied, ``instand_ws`` omitted) must evaluate
    ``4.4713 * I ** (2/3) / (60 - amb_t)``.

    Every case uses an intensity whose two-thirds power is an exact
    integer (see :data:`_EXACT_CUBE_INTENSITIES`), so the expected value
    is a product of three exactly representable factors written out in
    the parametrisation rather than a re-execution of the
    implementation.

    :param sfi: Surface fire intensity (kW/m).
    :param amb_t: Ambient temperature (C).
    :param expected: Hand-derived scorch height (m).
    :return: None. Raises via ``assert`` on mismatch.
    """
    _assert_close(float(calc_scorch_ht(sfi, amb_t)), expected)


@pytest.mark.parametrize("bad_input", [None, [None], [1.0, None]])
def test_scorch_ht_missing_intensity_guard_fires_for_object_dtype(bad_input):
    """
    The ``np.any(sfi == None)`` guard **does** fire for object-dtype
    inputs, contrary to a blanket "dead code" reading of Gate 0 finding
    **F-24**.

    ``np.asarray(None)`` and ``np.asarray([1.0, None])`` both produce
    object-dtype arrays, and NumPy compares object arrays against
    ``None`` element by element, so the guard raises exactly as intended
    for a genuinely missing intensity. F-24's precise claim - that the
    comparison "is never true for a numeric array" - is confirmed by the
    companion test below; the broader claim that the guard is dead code
    is not. See this module's docstring and the Phase 3 findings.

    :param bad_input: An input that produces an object-dtype array.
    :return: None. Raises via ``assert`` on mismatch.
    """
    with pytest.raises(Exception, match="Must enter a surface fire intensity"):
        calc_scorch_ht(bad_input)


def test_scorch_ht_missing_intensity_guard_is_inert_for_numeric_nan():
    """
    The same guard is inert for a float-dtype array: a NaN intensity is
    not caught and propagates through the equation, which is the half of
    Gate 0 finding **F-24** that is accurate as written.

    :return: None. Raises via ``assert`` on mismatch.
    """
    result = calc_scorch_ht(np.array([np.nan, 1000.0]))
    assert np.isnan(result[0])
    _assert_close(float(result[1]), 0.1483 * 100.0)


