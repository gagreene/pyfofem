import pyfofem.components.soil_heating as sh
from pyfofem.components.soil_heating import _SOIL_FAMILY_DEFAULTS, soil_heat_campbell

pytestmark = pytest.mark.soil_solver

#: 13 depths (cm), matching the Phase 5 BR-SOI-DUFF/NODUFF scenario
#: matrix's use of the C++ eC_Lay==14 (Surface + 13 layers) convention.
_DEPTHS = list(range(1, 14))

#: A short, clearly-decaying fire-intensity series (mirrors
#: ``_soil_campbell_contract.py``'s shared side-file formula so the same physical
#: scenario shape is exercised on both sides of the port, even though no
#: numeric comparison is attempted yet - see the module docstring).
_N_STEPS = 20
_TIMES_S = [i * 15.0 for i in range(_N_STEPS)]
_WL_SERIES = [max(0.0, 50.0 - 3.0 * i) for i in range(_N_STEPS)]
_HS_SERIES = [max(0.0, 10.0 - 0.5 * i) for i in range(_N_STEPS)]


def _duff_params(**overrides) -> dict:
    """
    Build a valid ``duff_params`` dict for :func:`soil_heat_campbell`'s
    ``model="duff"`` path, with optional field overrides.

    :param overrides: Fields to override in the base dict.
    :returns: A ``duff_params`` dict.
    """
    base = dict(duff_load=5.0, duff_depth=2.0, duff_moisture=60.0, pct_consumed=50.0)
    base.update(overrides)
    return base


def _soil_params(soil_family: str = "coarse-silty", start_water: float = 0.10,
                  start_temp: float = 21.0, **overrides) -> dict:
    """
    Build a valid ``soil_params`` dict for :func:`soil_heat_campbell`, with
    optional field overrides.

    ``"coarse-silty"`` is the default because it is the one soil family
    F-51 confirms has C++-matching physical constants - the most credible
    target for any future class (c) comparison built on top of this
    module's fixtures.

    :param soil_family: One of :data:`_SOIL_FAMILY_DEFAULTS`'s keys.
    :param start_water: Starting volumetric water content (m3/m3).
    :param start_temp: Starting soil temperature (degC).
    :param overrides: Additional fields to override in the base dict.
    :returns: A ``soil_params`` dict.
    """
    base = dict(soil_family=soil_family, start_water=start_water, start_temp=start_temp)
    base.update(overrides)
    return base


def test_both_routes_share_the_same_coupled_backend(monkeypatch):
    """Class (a) architecture invariant, added 2026-09-18 (F-70
    Campbell-backend consolidation pass). Both ``model="duff"`` and
    ``model="non_duff"`` must reach the exact same coupled-solver
    backend -- :func:`_run_coupled_soil_sim` (and, transitively,
    :func:`_soiltemp_step`) -- not two parallel implementations that
    happen to look similar. Proven by monkeypatching
    ``_run_coupled_soil_sim`` itself and recording the ``id()`` of the
    function object each route actually calls, rather than merely
    asserting the routes' outputs share a schema (already covered by
    :func:`test_duff_vs_non_duff_are_explicit_caller_choices_not_auto_routed`)."""
    calls = []
    real_run = sh._run_coupled_soil_sim

    def _spy(state, dt, forcing_fn, done_fn, start_temp):
        calls.append(id(_spy))
        return real_run(state, dt, forcing_fn, done_fn, start_temp)

    monkeypatch.setattr(sh, "_run_coupled_soil_sim", _spy)

    soil_heat_campbell("duff", _duff_params(), _soil_params(), _DEPTHS)
    soil_heat_campbell(
        "non_duff", {}, _soil_params(), _DEPTHS,
        burnup_intensity=_WL_SERIES, burnup_intensity_hs=_HS_SERIES,
        burnup_times=_TIMES_S,
    )

    assert len(calls) == 2
    assert calls[0] == calls[1] == id(_spy)


def test_diagnostic_hooks_default_to_no_op(monkeypatch):
    """Class (a) architecture invariant, added 2026-09-18 (F-70
    Campbell-backend consolidation pass). The public facade must never
    itself supply ``on_subiter``/``on_surface_update`` to
    :func:`_soiltemp_step` -- both diagnostic hooks stay at their
    ``None`` default for every real caller, so their presence in
    :func:`_campbell_newton_boundary_init`/
    :func:`_campbell_newton_node_update`'s extracted signatures changes
    nothing about ordinary behavior. Proven by monkeypatching
    ``_soiltemp_step`` itself and inspecting the actual keyword/
    positional arguments :func:`_run_coupled_soil_sim` passes it, rather
    than only reading the default-parameter source."""
    calls = []
    real_step = sh._soiltemp_step

    def _spy(state, r_rabs, dt, on_subiter=None, on_surface_update=None):
        calls.append((on_subiter, on_surface_update))
        return real_step(state, r_rabs, dt, on_subiter, on_surface_update)

    monkeypatch.setattr(sh, "_soiltemp_step", _spy)

    soil_heat_campbell("duff", _duff_params(), _soil_params(), _DEPTHS)

    assert len(calls) > 0
    assert all(hooks == (None, None) for hooks in calls)


def test_duff_route_produces_finite_dataframe():
    """Class (a). The ``model="duff"`` path must return a fully finite
    DataFrame (no NaN/Inf) - a solver instability would otherwise surface
    only as a silent downstream NaN."""
    df = soil_heat_campbell("duff", _duff_params(), _soil_params(), _DEPTHS)
    assert np.isfinite(df.to_numpy()).all()


def test_duff_vs_non_duff_are_explicit_caller_choices_not_auto_routed():
    """Class (a) contract note. Unlike C++'s SH_Mngr (which infers the
    route from duff_dep_pre_in > 0), soil_heat_campbell has no field that
    silently changes which model runs - passing "duff" always takes the
    duff-flux path and "non_duff" always takes the burnup-intensity path,
    regardless of what duff_params/burnup_* values happen to be set to."""
    duff_df = soil_heat_campbell("duff", _duff_params(), _soil_params(), _DEPTHS)
    non_duff_df = soil_heat_campbell(
        "non_duff", {}, _soil_params(), _DEPTHS,
        burnup_intensity=_WL_SERIES, burnup_intensity_hs=_HS_SERIES,
        burnup_times=_TIMES_S,
    )
    # Both routes are independently well-formed and are not required to
    # agree with each other - they model physically different surface
    # fluxes. The contract being tested is that each stays on its own path.
    assert list(duff_df.columns) == list(non_duff_df.columns)
    assert duff_df.index.name == non_duff_df.index.name == "time_min"


def test_first_recorded_row_is_post_first_step_not_raw_init():
    """Class (a). CORRECTED 2026-09-18 (F-70 comprehensive-suite
    reconciliation pass): this test's original name/assertion claimed
    every column at ``time_min == 0`` equals ``soil_params['start_temp']``
    exactly. That claim was itself wrong about the documented contract
    (see :func:`soil_heat_campbell`'s own docstring, corrected alongside
    this test): the first recorded row is the state after the FIRST
    Newton-converged timestep, not the raw pre-simulation initial
    condition -- matching the pinned C++ harness's own ``time_index == 0``
    convention exactly (independently verified: Phase 5 golden scenario
    SOI-NOD-01's own ``time_index=0`` surface reading is 38.849651 degC
    against a 21.0 degC harness ambient start, i.e. C++ ALSO reports a
    post-step value at index 0, never the raw ambient). This test now
    asserts the real, verifiable structural invariant instead: within one
    short timestep, diffusion has not yet reached the deep layers, so
    depth columns converge back toward ``start_temp`` monotonically with
    depth, and the deepest recorded depth is within a tight, physically
    expected tolerance of ``start_temp``. The surface column is
    deliberately NOT asserted to equal ``start_temp`` -- it is the one
    column guaranteed to have already moved."""
    df = soil_heat_campbell(
        "duff", _duff_params(), _soil_params(start_temp=17.5), _DEPTHS,
    )
    first_row = df.iloc[0].to_numpy()
    deviations = np.abs(first_row - 17.5)
    # Monotonic convergence toward start_temp with depth (index 0 = Surface,
    # increasing index = increasing depth) - each column is no farther from
    # start_temp than the previous, shallower one.
    assert np.all(np.diff(deviations) <= 1e-9)
    # The deepest recorded depth (13cm) has not been reached by one
    # timestep's diffusion and remains within a tight tolerance of
    # start_temp.
    assert deviations[-1] < 1e-4


