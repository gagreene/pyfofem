def test_zero_fire_intensity_never_exceeds_start_temp():
    """Class (a), oracle-independent physical invariant. A non_duff run
    with an all-zero fire-intensity series delivers zero surface flux, so
    the soil column must never exceed its own starting temperature (up to
    solver tolerance) - true regardless of which side (Python or C++, or
    neither) is scientifically "correct", since it follows from energy
    conservation alone, not from matching any oracle."""
    df = soil_heat_campbell(
        "non_duff", {}, _soil_params(start_temp=15.0), _DEPTHS,
        burnup_intensity=[0.0] * _N_STEPS, burnup_intensity_hs=[0.0] * _N_STEPS,
        burnup_times=_TIMES_S,
    )
    assert (df.to_numpy() <= 15.0 + 1e-6).all()
